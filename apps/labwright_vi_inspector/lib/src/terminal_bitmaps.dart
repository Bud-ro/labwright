BdTerminalArt? bdTerminalArtFor(ViDataType type, {required bool indicator}) {
  final folded = switch (type) {
    ViDataType.enumU16 || ViDataType.enumU32 => ViDataType.enumU8,
    _ => type,
  };
  return kBdTerminalArt[(folded, indicator)];
}

