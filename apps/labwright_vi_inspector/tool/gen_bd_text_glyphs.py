"""Writes lib/src/generated/bd_text_glyphs.dart: the block-diagram text font as bi-level glyph
bitmaps, rasterised by FreeType in mono mode with TrueType hinting at the diagram's pixel size.

    python3 tool/gen_bd_text_glyphs.py [font directory]

The font directory holds segoeui.ttf and segoeuib.ttf; it defaults to the Windows font folder
as seen from WSL. Each glyph is stored as its hinted advance, the row of its first ink below
the ascent line, and its rows as '#' and '.' with trailing blank columns trimmed.
"""

import os
import sys

from PIL import ImageFont

PPEM = 12
RANGES = [
    range(0x20, 0x7F),
    range(0xA0, 0x100),
    [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026],
    [0x2190, 0x2191, 0x2192, 0x2193, 0x2260, 0x2264, 0x2265, 0x221E],
    [0x03A9, 0x03BC],
]
FACES = [('Regular', 'segoeui.ttf'), ('Bold', 'segoeuib.ttf')]


def glyph(face, cp):
    ch = chr(cp)
    (one, _), _ = face.font.getsize(ch, '1')
    (two, _), _ = face.font.getsize(ch + ch, '1')
    advance = two - one
    mask = face.getmask(ch, mode='1')
    w, h = mask.size
    rows = [[1 if mask.getpixel((x, y)) > 127 else 0 for x in range(w)] for y in range(h)]
    while rows and rows[0] and all(r[-1] == 0 for r in rows):
        rows = [r[:-1] for r in rows]
    top = face.getbbox(ch)[1] if rows and rows[0] else 0
    return advance, top, [''.join('#' if v else '.' for v in r) for r in rows if r]


def main():
    font_dir = sys.argv[1] if len(sys.argv) > 1 else '/mnt/c/Windows/Fonts'
    out = os.path.join(os.path.dirname(__file__), '..', 'lib', 'src', 'generated', 'bd_text_glyphs.dart')
    lines = [
        '// GENERATED by tool/gen_bd_text_glyphs.py; do not edit.',
        '',
        '/// The block-diagram text font at [kBdTextGlyphPpem] pixels per em as bi-level glyphs:',
        '/// hinted advance, first ink row below the ascent line, and the rows as `#` and `.`',
        '/// joined by `|`.',
        'library;',
        '',
        f'const int kBdTextGlyphPpem = {PPEM};',
        '',
    ]
    for name, file in FACES:
        face = ImageFont.truetype(os.path.join(font_dir, file), PPEM, layout_engine=ImageFont.Layout.BASIC)
        ascent, descent = face.getmetrics()
        lines.append(f'const int kBdTextGlyphAscent{name} = {ascent};')
        lines.append(f'const int kBdTextGlyphDescent{name} = {descent};')
        lines.append('')
        lines.append(f'const Map<int, String> kBdTextGlyphs{name} = {{')
        for block in RANGES:
            for cp in block:
                advance, top, rows = glyph(face, cp)
                lines.append(f"  0x{cp:04x}: '{advance};{top};{'|'.join(rows)}',")
        lines.append('};')
        lines.append('')
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {os.path.normpath(out)}')


if __name__ == '__main__':
    main()
