import 'dart:io';

import 'package:image/image.dart' as img;

/// Writes lib/src/generated/prim_icon_art.dart from assets/prim_icons: one line per icon, its
/// pixel rows as palette characters, keyed by the asset's status key.
void main() {
  final dir = Directory('assets/prim_icons');
  final pattern = RegExp(
    r'^((?:prim|class)\d+(?:_t\d+)?)(?:_[a-z0-9-]+)?\.png$',
  );
  const transparent = '.';
  const letters = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
  final palette = <int, String>{};
  final art = <String, String>{};
  final files = dir.listSync().whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final match = pattern.firstMatch(file.uri.pathSegments.last);
    if (match == null) continue;
    final image = img
        .decodePng(file.readAsBytesSync())!
        .convert(numChannels: 4);
    final rgba = image.getBytes(order: img.ChannelOrder.rgba);
    final rows = StringBuffer();
    for (var y = 0; y < image.height; y++) {
      for (var x = 0; x < image.width; x++) {
        final i = (y * image.width + x) * 4;
        if (rgba[i + 3] == 0) {
          rows.write(transparent);
          continue;
        }
        final argb =
            0xff000000 | (rgba[i] << 16) | (rgba[i + 1] << 8) | rgba[i + 2];
        rows.write(palette[argb] ??= letters[palette.length]);
      }
      rows.write('|');
    }
    final key = match.group(1)!;
    final previous = art[key];
    if (previous != null && previous != '$rows') {
      throw StateError(
        '$key has two assets with different pixels: ${file.path}',
      );
    }
    art[key] = '$rows';
  }
  final colours = palette.entries.toList()
    ..sort((a, b) => a.value.compareTo(b.value));
  final out = File('lib/src/generated/prim_icon_art.dart');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync('''
// Generated by tool/gen_prim_icon_art.dart from assets/prim_icons; do not edit.
// dart format off

/// The ARGB colour of each character in a [kPrimIconArt] row; '$transparent' is transparent.
const Map<String, int> kPrimIconPalette = {
  '$transparent': 0x00000000,
${colours.map((e) => "  '${e.value}': 0x${e.key.toRadixString(16).padLeft(8, '0')},").join('\n')}
};

/// Each primitive icon's pixels by its status key: rows of palette characters, each row ending
/// in '|'.
const Map<String, String> kPrimIconArt = {
${art.entries.map((e) => "  '${e.key}': '${e.value}',").join('\n')}
};
''');
  stdout.writeln(
    'wrote ${art.length} icons in ${colours.length} colours to ${out.path}',
  );
}
