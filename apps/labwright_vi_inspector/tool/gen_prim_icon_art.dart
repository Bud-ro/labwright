import 'dart:convert';
import 'dart:io';

import 'package:image/image.dart' as img;

/// Writes lib/src/generated/prim_icon_art.dart from assets/prim_icons: every icon's pixels with
/// transparent ones zeroed, deflated and base64-encoded, so the app decodes them without an
/// asset read.
void main() {
  final dir = Directory('assets/prim_icons');
  final pattern = RegExp(
    r'^((?:prim|class)\d+(?:_t\d+)?)(?:_[a-z0-9-]+)?\.png$',
  );
  final entries = <String>[];
  final files = dir.listSync().whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final name = file.uri.pathSegments.last;
    final match = pattern.firstMatch(name);
    if (match == null) continue;
    final image = img
        .decodePng(file.readAsBytesSync())!
        .convert(numChannels: 4);
    final rgba = image.getBytes(order: img.ChannelOrder.rgba);
    for (var i = 0; i < rgba.length; i += 4) {
      if (rgba[i + 3] == 0) rgba[i] = rgba[i + 1] = rgba[i + 2] = 0;
    }
    final packed = base64Encode(ZLibEncoder(level: 9).convert(rgba));
    entries.add(
      "  PrimIconArtSource('${match.group(1)}', ${image.width}, ${image.height}, '$packed'),",
    );
  }
  final out = File('lib/src/generated/prim_icon_art.dart');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync('''
// Generated by tool/gen_prim_icon_art.dart from assets/prim_icons; do not edit.

/// One primitive icon asset: its status key and its RGBA pixels, row-major, deflated and
/// base64-encoded.
class PrimIconArtSource {
  const PrimIconArtSource(this.key, this.width, this.height, this.packedRgba);

  final String key;

  final int width;

  final int height;

  final String packedRgba;
}

const List<PrimIconArtSource> kPrimIconArtSources = [
${entries.join('\n')}
];
''');
  stdout.writeln('wrote ${entries.length} icons to ${out.path}');
}
