import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:image/image.dart' as img;

/// Writes lib/src/generated/prim_icon_atlas.dart from assets/prim_icons: every icon's pixels on
/// one sheet, each icon ringed by a copy of its own edge pixels and a clear line, with the
/// per-icon measurements the painters need.
void main() {
  final dir = Directory('assets/prim_icons');
  final pattern = RegExp(
    r'^((?:prim|class)\d+(?:_t\d+)?)(?:_[a-z0-9-]+)?\.png$',
  );
  final icons = <_Icon>[];
  final files = dir.listSync().whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final match = pattern.firstMatch(file.uri.pathSegments.last);
    if (match == null) continue;
    final image = img
        .decodePng(file.readAsBytesSync())!
        .convert(numChannels: 4);
    final rgba = image.getBytes(order: img.ChannelOrder.rgba);
    for (var i = 0; i < rgba.length; i += 4) {
      if (rgba[i + 3] == 0) rgba[i] = rgba[i + 1] = rgba[i + 2] = 0;
    }
    icons.add(_Icon(match.group(1)!, image.width, image.height, rgba));
  }
  const sheetWidth = 512;
  final byHeight = [...icons]..sort((a, b) => b.height.compareTo(a.height));
  var x = 0, y = 0, rowHeight = 0;
  for (final icon in byHeight) {
    final cellWidth = icon.width + 3, cellHeight = icon.height + 3;
    if (x + cellWidth > sheetWidth) {
      x = 0;
      y += rowHeight;
      rowHeight = 0;
    }
    icon.left = x + 1;
    icon.top = y + 1;
    x += cellWidth;
    if (cellHeight > rowHeight) rowHeight = cellHeight;
  }
  final sheetHeight = (y + rowHeight + 15) & ~15;
  final sheet = Uint8List(sheetWidth * sheetHeight * 4);
  for (final icon in icons) {
    for (var sy = -1; sy <= icon.height; sy++) {
      for (var sx = -1; sx <= icon.width; sx++) {
        final ix = sx.clamp(0, icon.width - 1),
            iy = sy.clamp(0, icon.height - 1);
        final from = (iy * icon.width + ix) * 4;
        final to = ((icon.top + sy) * sheetWidth + icon.left + sx) * 4;
        sheet.setRange(to, to + 4, icon.rgba, from);
      }
    }
  }
  final packed = base64Encode(ZLibEncoder(level: 9).convert(sheet));
  final entries = [
    for (final icon in icons)
      '  PrimIconAtlasEntry(\n'
          "    '${icon.key}',\n"
          '    ${icon.left},\n'
          '    ${icon.top},\n'
          '    ${icon.width},\n'
          '    ${icon.height},\n'
          '    ${icon.inkBounds},\n'
          '    ${icon.cornerAa},\n'
          '  ),',
  ];
  final out = File('lib/src/generated/prim_icon_atlas.dart');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync('''
// Generated by tool/gen_prim_icon_atlas.dart from assets/prim_icons; do not edit.

/// One primitive icon on the atlas sheet: its status key, its pixel rectangle on the sheet, the
/// bounds of its opaque pixels within the icon, and the indices of its anti-aliased corner
/// pixels (opaque 0xdddddd pixels on the icon's outline).
class PrimIconAtlasEntry {
  const PrimIconAtlasEntry(
    this.key,
    this.left,
    this.top,
    this.width,
    this.height,
    this.inkBounds,
    this.cornerAa,
  );

  final String key;

  final int left;

  final int top;

  final int width;

  final int height;

  final ({int left, int top, int right, int bottom})? inkBounds;

  final List<int> cornerAa;
}

const int kPrimIconAtlasWidth = $sheetWidth;

const int kPrimIconAtlasHeight = $sheetHeight;

/// The sheet's RGBA pixels, row-major, deflated and base64-encoded; every pixel is fully opaque
/// or fully transparent, and each icon is ringed by a copy of its own edge pixels.
const String kPrimIconAtlasRgba = '$packed';

const List<PrimIconAtlasEntry> kPrimIconAtlas = [
${entries.join('\n')}
];
''');
  stdout.writeln(
    'wrote ${icons.length} icons on a $sheetWidth x $sheetHeight sheet to ${out.path}',
  );
}

class _Icon {
  _Icon(this.key, this.width, this.height, this.rgba);

  final String key;

  final int width;

  final int height;

  final Uint8List rgba;

  int left = 0;

  int top = 0;

  int alphaAt(int x, int y) => x < 0 || y < 0 || x >= width || y >= height
      ? 0
      : rgba[(y * width + x) * 4 + 3];

  String get inkBounds {
    var minX = width, minY = height, maxX = -1, maxY = -1;
    for (var y = 0; y < height; y++) {
      for (var x = 0; x < width; x++) {
        if (alphaAt(x, y) == 0) continue;
        if (x < minX) minX = x;
        if (y < minY) minY = y;
        if (x > maxX) maxX = x;
        if (y > maxY) maxY = y;
      }
    }
    return maxX < minX
        ? 'null'
        : '(left: $minX, top: $minY, right: ${maxX + 1}, bottom: ${maxY + 1})';
  }

  List<int> get cornerAa => [
    for (var y = 0; y < height; y++)
      for (var x = 0; x < width; x++)
        if (alphaAt(x, y) == 255 &&
            rgba[(y * width + x) * 4] == 0xdd &&
            rgba[(y * width + x) * 4 + 1] == 0xdd &&
            rgba[(y * width + x) * 4 + 2] == 0xdd &&
            (alphaAt(x - 1, y) == 0 ||
                alphaAt(x + 1, y) == 0 ||
                alphaAt(x, y - 1) == 0 ||
                alphaAt(x, y + 1) == 0))
          y * width + x,
  ];
}
