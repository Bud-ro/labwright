        if (step.name == key.value || step.id == key.value) step,
    ];
    final variable = matches.length == 1 ? _resultVars[matches.single.raw] : null;
    return variable == null ? null : (code: variable, type: _DartSlot.untyped, prec: _Prec.primary);
  }

  static final _literalCode = RegExp(r"^(?:true|false|null|-?\d+(?:\.\d+)?|'(?:[^'\\]|\\.)*')$");

  _Code? _elementTarget(String? element) {
    final parsed = element == null ? null : parseSeqExpression(element);
    final target = parsed == null ? null : _emitTarget(parsed);
    return target == null || target.type == _DartSlot.absent || target.type == _DartSlot.opaque ? null : target;
  }

  _Code? _emitTarget(SeqExpr e) => switch (e) {
    SeqMember() || SeqIndex() => _emit(e),
    _ => null,
  };

  _Code? _emit(SeqExpr e) {
    switch (e) {
      case SeqNumber(:final value, :final integral):
        return (
          code: integral ? value.toString() : _numLiteral(value.toDouble()),
          type: integral ? _DartSlot.integer : _DartSlot.number,
          prec: _Prec.primary,
        );
      case SeqString(:final value):
        return (code: "'${_escape(value)}'", type: _DartSlot.text, prec: _Prec.primary);
      case SeqBool(:final value):
        return (code: '$value', type: _DartSlot.flag, prec: _Prec.primary);
      case SeqNothing():
        return (code: 'null', type: _DartSlot.absent, prec: _Prec.primary);
      case SeqName() || SeqSequence():
        return null;
      case SeqMember(:final target, :final name):
        final folded = _foldedStepProperty(e);
        if (folded != null) return folded;
        if (target is SeqIndex && name.toLowerCase() == 'result') {
          final ref = _stepResultRef(target);
          if (ref != null) return ref;
        }
        if (target is SeqName) {
          final root = _rootOf(target.name);
          return root == null ? null : _emitRooted(root, name);
        }
        final base = _emit(target);
        if (base == null || base.type != _DartSlot.untyped || _dartReservedWords.contains(name)) return null;
        return (code: '${_wrap(base, _Prec.primary).code}.$name', type: _DartSlot.untyped, prec: _Prec.primary);
      case SeqIndex(:final target, :final index):
        final base = _emit(target);
        final at = _emit(index);
        if (base == null || at == null) return null;
        final indexable =
            (base.type == _DartSlot.list && (_isNumeric(at.type) || at.type == _DartSlot.untyped)) ||
            (base.type == _DartSlot.untyped && at.type != _DartSlot.opaque && at.type != _DartSlot.absent);
        if (!indexable) return null;
        final key = at.type == _DartSlot.number ? '${_wrap(at, _Prec.primary).code}.toInt()' : at.code;
        return (code: '${_wrap(base, _Prec.primary).code}[$key]', type: _DartSlot.untyped, prec: _Prec.primary);
      case SeqCall(:final callee, :final arguments):
        return _emitCall(callee, arguments);
      case SeqUnary(:final op, :final operand):
        final inner = _emit(operand);
        if (inner == null) return null;
        switch (op) {
          case SeqUnaryOp.not:
            final b = _asBool(inner);
            return b == null
                ? null
                : (code: '!${_wrap(b, _Prec.prefix).code}', type: _DartSlot.flag, prec: _Prec.prefix);
          case SeqUnaryOp.negate || SeqUnaryOp.plus:
            if (!_isNumeric(inner.type) && inner.type != _DartSlot.untyped) return null;
            if (op == SeqUnaryOp.plus) return inner;
            final operand = inner.code.startsWith('-') ? '(${inner.code})' : _wrap(inner, _Prec.prefix).code;
            return (code: '-$operand', type: inner.type, prec: _Prec.prefix);
          case SeqUnaryOp.bitNot:
            if (inner.type != _DartSlot.integer) return null;
            return (code: '~${_wrap(inner, _Prec.prefix).code}', type: _DartSlot.integer, prec: _Prec.prefix);
        }
      case SeqStep(:final target, :final increment, :final prefix):
        final t = _emitTarget(target);
        if (t == null || !(_isNumeric(t.type) || t.type == _DartSlot.untyped)) return null;
        final op = increment ? '++' : '--';
        return (
          code: prefix ? '$op${t.code}' : '${t.code}$op',
          type: t.type,
          prec: prefix ? _Prec.prefix : _Prec.primary,
        );
      case SeqBinary(:final op, :final left, :final right):
        final l = _emit(left);
        final r = _emit(right);
        return l == null || r == null ? null : _emitBinary(op, l, r);
      case SeqConditional(:final condition, :final whenTrue, :final whenFalse):
        final c = _emit(condition);
        final cb = c == null ? null : _asBool(c);
        var t = _emit(whenTrue);
        var f = _emit(whenFalse);
        if (cb == null || t == null || f == null) return null;
        if (cb.code == 'true') return t;
        if (cb.code == 'false') return f;
        _DartSlot type;
        if (t.type == f.type) {
          type = t.type;
        } else if (t.type == _DartSlot.untyped || f.type == _DartSlot.untyped) {
          type = _DartSlot.untyped;
        } else if (_isNumeric(t.type) && _isNumeric(f.type)) {
          type = _DartSlot.number;
          t = _coerce(t, type)!;
          f = _coerce(f, type)!;
        } else {
          type = _DartSlot.opaque;
        }
        return (
          code: '${_wrap(cb, _Prec.ifNull).code} ? ${_wrap(t, _Prec.ifNull).code} : ${_wrap(f, _Prec.ifNull).code}',
          type: type,
          prec: _Prec.conditional,
        );
      case SeqAssign(:final op, :final target, :final value):
        final t = _emitTarget(target);
        final v = _emit(value);
        if (t == null || v == null) return null;
        if (!identical(e, _statementRoot) && _writeOnly.contains(t.code)) return v;
        final binary = op.binary;
        if (binary == null) {
          final coerced = _coerce(v, t.type);
          if (coerced == null) return null;
          return (code: '${t.code} = ${_wrap(coerced, _Prec.assignment).code}', type: t.type, prec: _Prec.assignment);
        }
        final combined = _emitBinary(binary, t, v);
        if (combined == null || _coerce(combined, t.type) != combined) return null;
        if (binary == SeqBinaryOp.modulo) {
          return (code: '${t.code} = ${combined.code}', type: t.type, prec: _Prec.assignment);
        }
        return (code: '${t.code} ${op.token} ${_wrap(v, _Prec.assignment).code}', type: t.type, prec: _Prec.assignment);
      case SeqArray(:final elements):
        final items = [for (final element in elements) _emit(element)];
        if (items.contains(null)) return null;
        return (code: '<dynamic>[${items.map((i) => i!.code).join(', ')}]', type: _DartSlot.list, prec: _Prec.primary);
    }
  }

  static bool _pure(String code) => !RegExp(r'\(|(?<![=!<>])=(?!=)|\+\+|--').hasMatch(code);

  static bool _isStringCode(_Code c) =>
      c.type == _DartSlot.text &&
      c.prec == _Prec.primary &&
      c.code.length > 1 &&
      c.code.startsWith("'") &&
      c.code.endsWith("'");

  static String? _interpolated(_Code l, _Code r) {
    if (!_isStringCode(l) && !_isStringCode(r)) return null;
    String part(_Code c, String next) {
      if (_isStringCode(c)) return c.code.substring(1, c.code.length - 1);
      final code = c.type == _DartSlot.untyped ? '${c.code} as String' : c.code;
      return RegExp(r'^[A-Za-z_]\w*$').hasMatch(code) && !RegExp(r'^\w').hasMatch(next) ? '\$$code' : '\${$code}';
    }

    final tail = part(r, '');
    var head = part(l, tail);
    if (RegExp(r'^\w').hasMatch(tail)) {
      head = head.replaceFirstMapped(RegExp(r'(?<!\\)\$([A-Za-z_]\w*)$'), (m) => '\${${m[1]}}');
    }
    return "'$head$tail'";
  }

  _Code? _emitBinary(SeqBinaryOp op, _Code l, _Code r) {
    _Code out(String code, _DartSlot type, int prec) => (code: code, type: type, prec: prec);
    String infix(int prec) => '${_wrap(l, prec).code} ${op.token} ${_wrap(r, prec + 1).code}';
    final dyn = l.type == _DartSlot.untyped || r.type == _DartSlot.untyped;
    final numeric = _isNumeric(l.type) && _isNumeric(r.type);
    final bothInt = l.type == _DartSlot.integer && r.type == _DartSlot.integer;
    bool operable({required bool text}) {
      if (numeric) return true;
      if (!dyn) return false;
      final other = l.type == _DartSlot.untyped ? r.type : l.type;
      return _isNumeric(other) || other == _DartSlot.untyped || (text && other == _DartSlot.text);
    }

    _DartSlot arithmetic() => l.type == _DartSlot.untyped
        ? _DartSlot.untyped
        : dyn
        ? _DartSlot.opaque
        : bothInt
        ? _DartSlot.integer
        : _DartSlot.number;
    switch (op) {
      case SeqBinaryOp.or || SeqBinaryOp.and:
        final lb = _asBool(l);
        final rb = _asBool(r);
        if (lb == null || rb == null) return null;
        final absorbing = op == SeqBinaryOp.or ? 'true' : 'false';
        final neutral = op == SeqBinaryOp.or ? 'false' : 'true';
        if (lb.code == neutral) return rb;
        if (rb.code == neutral) return lb;
        if (lb.code == absorbing) return lb;
        if (rb.code == absorbing && _pure(lb.code)) return rb;
        final prec = op == SeqBinaryOp.or ? _Prec.or : _Prec.and;
        return out('${_wrap(lb, prec).code} ${op.token} ${_wrap(rb, prec + 1).code}', _DartSlot.flag, prec);
      case SeqBinaryOp.equal || SeqBinaryOp.notEqual:
        if (_literalCode.hasMatch(l.code) &&
            _literalCode.hasMatch(r.code) &&
            l.type == r.type &&
            l.type != _DartSlot.absent) {
          final same = l.type == _DartSlot.text || l.type == _DartSlot.flag
              ? l.code == r.code
              : num.parse(l.code) == num.parse(r.code);
          return out('${same == (op == SeqBinaryOp.equal)}', _DartSlot.flag, _Prec.primary);
        }
        return out(
          '${_wrap(l, _Prec.relational).code} ${op.token} ${_wrap(r, _Prec.relational).code}',
          _DartSlot.flag,
          _Prec.equality,
        );
      case SeqBinaryOp.less || SeqBinaryOp.lessEqual || SeqBinaryOp.greater || SeqBinaryOp.greaterEqual:
        if (!operable(text: false)) return null;
        return out(
          '${_wrap(l, _Prec.bitOr).code} ${op.token} ${_wrap(r, _Prec.bitOr).code}',
          _DartSlot.flag,
          _Prec.relational,
        );
      case SeqBinaryOp.add:
        if ((l.type == _DartSlot.text && (r.type == _DartSlot.text || r.type == _DartSlot.untyped)) ||
            (l.type == _DartSlot.untyped && _isStringCode(r))) {
          final interpolation = _interpolated(l, r);
          return interpolation != null
              ? out(interpolation, _DartSlot.text, _Prec.primary)
              : out(infix(_Prec.additive), _DartSlot.text, _Prec.additive);
        }
        if (!operable(text: true)) return null;
        return out(infix(_Prec.additive), arithmetic(), _Prec.additive);
      case SeqBinaryOp.subtract || SeqBinaryOp.multiply || SeqBinaryOp.divide:
        if (!operable(text: false)) return null;
        final prec = op == SeqBinaryOp.subtract ? _Prec.additive : _Prec.multiplicative;
        final type = op == SeqBinaryOp.divide && numeric ? _DartSlot.number : arithmetic();
        return out(infix(prec), type, prec);
      case SeqBinaryOp.modulo:
        if (!numeric) return null;
        return out('${_wrap(l, _Prec.primary).code}.remainder(${r.code})', arithmetic(), _Prec.primary);
      case SeqBinaryOp.bitAnd ||
          SeqBinaryOp.bitOr ||
          SeqBinaryOp.bitXor ||
          SeqBinaryOp.shiftLeft ||
          SeqBinaryOp.shiftRight:
        if (!bothInt) return null;
        final prec = switch (op) {
          SeqBinaryOp.bitAnd => _Prec.bitAnd,
          SeqBinaryOp.bitXor => _Prec.bitXor,
          SeqBinaryOp.bitOr => _Prec.bitOr,
          _ => _Prec.shift,
        };
        return out(infix(prec), _DartSlot.integer, prec);
    }
  }

  _Code? _emitCall(SeqExpr callee, List<SeqExpr> arguments) {
    if (callee is SeqMember) {
      final base = callee.target is SeqName ? null : _emit(callee.target);
      if (base == null || base.type != _DartSlot.untyped || _dartReservedWords.contains(callee.name)) return null;
      final args = [for (final a in arguments) _emit(a)];
      if (args.any((a) => a == null)) return null;
      return (
        code: '${_wrap(base, _Prec.primary).code}.${callee.name}(${args.map((a) => a!.code).join(', ')})',
        type: _DartSlot.untyped,
        prec: _Prec.primary,
      );
    }
    if (callee is! SeqName) return null;
    final function = _SeqFunction.byName[callee.name];
    if (function == null || arguments.length < function.minArgs || arguments.length > function.maxArgs) return null;
    if (function == _SeqFunction.nameOf) {
      final subject = arguments.single;
      final step = _foldStep;
      if (step == null || subject is! SeqName || subject.name.toLowerCase() != 'step') return null;
      return (code: "'${_escape(step.name)}'", type: _DartSlot.text, prec: _Prec.primary);
    }
    if (function == _SeqFunction.evaluate) {
      final source = arguments.single;
      final text = source is SeqString ? source.value : _stepLeaf(source)?.scalar;
      if (text == null) return null;
      final parsed = parseSeqExpression(text);
      return parsed == null || parsed is SeqSequence ? null : _emit(parsed);
    }
    final args = [for (final a in arguments) _emit(a)];
    if (args.any((a) => a == null)) return null;
    final codes = [for (final a in args) a!];
    if (function == _SeqFunction.allOf || function == _SeqFunction.anyOf) {
      if (arguments.any(_hasEffects)) return null;
      final bools = [for (final c in codes) _asBool(c)];
      if (bools.any((b) => b == null)) return null;
      final prec = function == _SeqFunction.allOf ? _Prec.and : _Prec.or;
      final joiner = function == _SeqFunction.allOf ? ' && ' : ' || ';
      return (code: bools.map((b) => _wrap(b!, prec + 1).code).join(joiner), type: _DartSlot.flag, prec: prec);
    }
    if (function == _SeqFunction.random && codes.any((c) => !_isNumeric(c.type) && c.type != _DartSlot.untyped)) {
      return null;
    }
    final name = 'ts.${function.dart}';
    return (code: '$name(${codes.map((c) => c.code).join(', ')})', type: function.result, prec: _Prec.primary);
  }

  static bool _hasEffects(SeqExpr e) => switch (e) {
    SeqCall(:final callee, :final arguments) =>
      callee is! SeqName ||
          !const {
            _SeqFunction.len,
            _SeqFunction.getNumElements,
            _SeqFunction.str,
            _SeqFunction.left,
            _SeqFunction.right,
            _SeqFunction.mid,
            _SeqFunction.find,
            _SeqFunction.allOf,
            _SeqFunction.anyOf,
          }.contains(_SeqFunction.byName[callee.name]) ||
          arguments.any(_hasEffects),
    SeqAssign() || SeqStep() => true,
    SeqMember(:final target) => _hasEffects(target),
    SeqIndex(:final target, :final index) => _hasEffects(target) || _hasEffects(index),
    SeqUnary(:final operand) => _hasEffects(operand),
    SeqBinary(:final left, :final right) => _hasEffects(left) || _hasEffects(right),
    SeqConditional(:final condition, :final whenTrue, :final whenFalse) =>
      _hasEffects(condition) || _hasEffects(whenTrue) || _hasEffects(whenFalse),
    SeqArray(:final elements) => elements.any(_hasEffects),
    SeqSequence() => true,
    _ => false,
  };

  void _emitSequence(Sequence sequence, _SeqScope scope) {
    final fnName = _sequenceFnNames[sequence.name]!;
    _out.writeln(
      '/// Sequence `${_comment(sequence.name)}`'
      '${sequence.comment != null ? ' — ${_comment(sequence.comment!)}' : ''}.',
    );

    _usedIds = <String>{..._topLevelNames, ...scope.allIds};
    final emittedParams = scope.emittedParams;
    _paramIds = scope.paramIds;
    final emittedLocals = scope.emittedLocals;
    _localIds = scope.localIds;
    _idTypes = {..._fileGlobalTypes, ...scope.idTypes};

    final params = [
      for (final p in emittedParams)
        if (scope.boxedIds.contains(_paramIds[p.name]))
          'ts.Ref<${_idTypes[_paramIds[p.name]]!.source}>? ${_paramIds[p.name]}'
        else
          _paramDecl(p, _paramIds[p.name]!),
    ];
    _out.writeln(
      'Future<String> $fnName('
      '${params.isEmpty ? '' : '{${params.join(', ')}}'}) async {',
    );
    _indent = 1;
    _sequence = sequence;
    _runId = _claimId('run');
    _resultVars = _trackedResults(sequence);

    var preamble = false;
    _boxedParams = {};
    final boxes = <String, String>{};
    for (final p in emittedParams) {
      final id = _paramIds[p.name]!;
      if (_scalarType(p) == null && _isArrayVar(p)) {
        _line('$id ??= ${_arrayInit(p)};${_typeComment(p)}');
        preamble = true;
      }
      if (scope.boxedIds.contains(id)) {
        final (type, _, init) = _scalarDecl(p, id)!;
        final box = _claimId('${id}Ref');
        boxes[box] = 'final $box = $id ?? ts.Ref<${type.source}>($init);';
        _boxedParams[id] = box;
        _boxTypes[box] = type;
      } else if (_scalarType(p) == null && !p.passesByReference) {
        _line('$id = ts.copy($id);');
        preamble = true;
      }
    }
    if (preamble) _line('');
    final locals = {for (final local in emittedLocals) _localIds[local.name]!: local};
    final results = {for (final step in sequence.steps) ?_resultVars[step.raw]: step};
    final (assigned, read) = _scanLocals(sequence, locals);
    _writeOnly = {
      for (final id in locals.keys)
        if (assigned.contains(id) && !read.contains(id)) id,
    };
    for (final MapEntry(key: box, value: line) in boxes.entries) {
      if (read.contains(box)) _line(line);
    }
    for (final MapEntry(key: id, value: local) in locals.entries) {
      if (read.contains(id)) _line(_localDecl(local, id, assigned.contains(id)));
    }
    if ([...boxes.keys, ...locals.keys].any(read.contains)) _line('');
    _line('final $_runId = ts.SequenceRun();');
    for (final MapEntry(key: id, value: step) in results.entries) {
      _line(
        '${assigned.contains(id) ? '' : 'final '}dynamic $id = ${_resultInit(step)}; // result of ${_comment(step.name)}',
      );
    }
    _line('');
    _emitBody(sequence);
    _line('return $_runId.status;');
    _indent = 0;
    _out
      ..writeln('}')
      ..writeln();
    _sequence = null;
    _resultVars = Map.identity();
    _localIds = const {};
    _paramIds = const {};
    _idTypes = const {};
  }

  Map<String, String> _constLocals = const {};
  Set<String> _writeOnly = const {};

  (Set<String>, Set<String>) _scanLocals(Sequence sequence, Map<String, SeqVariable> locals) {
    _constLocals = const {};
    _writeOnly = const {};
    final code = StringBuffer();
    final calls = <Step>[];
    final reinitialized = <String>{};
    void statements(String? raw) => raw == null ? null : _stmtParts(raw).forEach(code.writeln);
    const loops = {FlowKind.whileLoop, FlowKind.doWhile, FlowKind.forLoop, FlowKind.forEach, FlowKind.sweepLoop};
    final usedIds = {..._usedIds};
    final targetsCleanup = sequence.steps.any((s) => s.settings.isNormalMode && _targetsCleanup(s));
    for (final group in StepGroup.values) {
      final open = <FlowKind>[];
      _group = group;
      _gotoLabels = _gotoPlan(sequence.stepsIn(group)).sites;
      _bodyLabel = group != StepGroup.cleanup && (sequence.cleanup.isNotEmpty || targetsCleanup) ? 'body' : null;
      for (final step in sequence.stepsIn(group)) {
        final flow = step.flowControl;
        final structural = flow != null && flow.kind != FlowKind.breakStmt && flow.kind != FlowKind.continueStmt;
        if (!step.settings.isNormalMode && !structural) continue;
        final precondition = step.settings.precondition ?? _typePreconditions[step.type];
        switch (flow?.kind) {
          case FlowKind.ifBlock || FlowKind.elseIf || FlowKind.whileLoop || FlowKind.doWhile:
            code.writeln(_cond(flow!.condition ?? 'true'));
          case FlowKind.forLoop:
            statements(flow!.initialization);
            statements(flow.increment);
            code.writeln(_cond(flow.condition ?? 'true'));
          case FlowKind.forEach:
            code.writeln(_expr(flow!.arrayExpr ?? '[]'));
            if (_elementTarget(flow.arrayElement) case final target?) code.writeln('${target.code} = element;');
          case FlowKind.selectBlock || FlowKind.caseBlock:
            code.writeln(_expr(flow!.itemExpression ?? 'null'));
          case FlowKind.breakStmt || FlowKind.continueStmt:
            if (precondition != null) code.writeln(_cond(precondition));
          case FlowKind.sweepLoop:
            for (final parameter in [...?_sweepLevels(step.sweepLoop!)?.expand((level) => level)]) {
              code
                ..writeln(parameter.values)
                ..writeln(parameter.bind('value'));
            }
          case null:
            final result = _resultVars[step.raw];
            final looping = step.settings.isLooping && result != null;
            if (result != null && (looping || open.any(loops.contains))) reinitialized.add(result);
            _foldStep = step;
            _foldResult = result;
            if (precondition != null) code.writeln(_cond(precondition));
            if (looping) {
              _stepLoop = 'loop';
              statements(step.settings.loopInitialize);
              code.writeln(_cond(step.settings.loopWhile ?? 'true'));
              statements(step.settings.loopIncrement);
              if (step.settings.loopStatus case final status?) code.writeln(_expr(status));
            }
            statements(step.settings.preExpression);
            statements(step.settings.postExpression);
            final timeout = step.timeoutExpression ?? step.waitTimeExpression;
            if (step.stepType == StepType.wait && timeout != null && num.tryParse(timeout.trim()) == null) {
              code.writeln(_expr(timeout));
            }
            if (_statusExpression(step) case final status? when result != null) {
              final pieces = _rawStmtPieces(status) ?? [status];
              pieces.take(pieces.length - 1).forEach(statements);
              code.writeln(_expr(pieces.last));
            }
            if (step.type == _messagePopupType && _hostedPhases(step).contains(_SubstepKind.post)) {
              for (final raw in [
                step.popupTitleExpression,
                step.popupMessageExpression,
                step.popupDefaultResponseExpression,
                for (var i = 1; i <= _popupButtonCount; i++) step.raw.prop('Button${i}Label')?.scalar,
              ].nonNulls) {
                code.writeln(_expr(raw));
              }
            }
            final custom = step.settings.customExpression;
            final actions = [
              for (final (action, target) in _postActions(step.settings)) _postActionCode(step, action, target),
            ];
            if (custom != null && !actions.contains(null) && actions.any((a) => a != '')) {
              code.writeln(_condition(custom));
            }
            _stepLoop = null;
            _foldStep = null;
            _foldResult = null;
            if (step.module.adapter == SeqAdapter.sequenceCall) calls.add(step);
          default:
        }
        switch (flow?.kind) {
          case FlowKind.end when open.isNotEmpty:
            open.removeLast();
          case final kind? when kind == FlowKind.ifBlock || kind == FlowKind.selectBlock || loops.contains(kind):
            open.add(kind);
          case FlowKind.caseBlock when open.contains(FlowKind.selectBlock):
            open.add(FlowKind.caseBlock);
          default:
        }
      }
    }
    _gotoLabels = Map.identity();
    _bodyLabel = null;
    for (final step in calls) {
      _sequenceCall(step).args.after.forEach(code.writeln);
    }
    final (assigned, read) = _accesses(code.toString());
    _constLocals = {
      for (final MapEntry(key: id, value: local) in locals.entries)
        if (!assigned.contains(id))
          if (_constInit(local) case final init?) id: init,
    };
    for (final step in calls) {
      final args = _sequenceCall(step).args;
      read.addAll(_accesses([args.text, ...args.before].join('\n')).$2);
    }
    _usedIds = usedIds;
    return (assigned..addAll(reinitialized), read);
  }

  bool _isNullLocal(SeqVariable local) {
    final cls = local.raw.valueClass;
    return !_isArrayVar(local) && (cls == SeqValueClass.reference || (cls == null && local.raw.subProps.isEmpty));
  }

  String? _constInit(SeqVariable local) => switch (_scalarDecl(local, _localIds[local.name]!)) {
    (_, _, final init) => init,
    null => _isNullLocal(local) ? 'null' : null,
  };

  void _emitBody(Sequence sequence) {
    final nonEmptyGroups = [
      for (final g in StepGroup.values)
        if (sequence.stepsIn(g).isNotEmpty) g,
    ];
    if (nonEmptyGroups.isEmpty) {
      _line('// (no steps in the source sequence)');
      _line('');
    }
    final cleanup = sequence.cleanup;
    final bodyGroups = [
      for (final g in nonEmptyGroups)
        if (g != StepGroup.cleanup) g,
    ];
    final wantsBody = cleanup.isNotEmpty || bodyGroups.any((g) => sequence.stepsIn(g).any(_targetsCleanup));
    _bodyLabel = wantsBody && bodyGroups.isNotEmpty ? _claimId('body') : null;
    _cleanupEntriesOf = _bodyLabel != null && cleanup.isNotEmpty ? _cleanupEntries(sequence) : const {};
    _cleanupFrom = _cleanupEntriesOf.isEmpty ? null : _claimId('cleanupFrom');
    if (_cleanupFrom != null) _line('var $_cleanupFrom = 0;');
    final bodyAt = _out.length + 2 * _indent;
    if (_bodyLabel != null) {
      _line(cleanup.isNotEmpty ? '$_bodyLabel: try {' : '$_bodyLabel: {');
      _indent++;
    }
    for (final group in bodyGroups) {
      if (nonEmptyGroups.length > 1) _line('// ── ${group.name} ──');
      _group = group;
      _emitSteps(sequence.stepsIn(group));
      _line('');
    }
    if (_bodyLabel != null) {
      _indent--;
      _line(cleanup.isNotEmpty ? '} finally {' : '}');
    }
    if (cleanup.isNotEmpty) {
      if (_bodyLabel != null) _indent++;
      if (nonEmptyGroups.length > 1) _line('// ── ${StepGroup.cleanup.name} ──');
      _group = StepGroup.cleanup;
      _emitSteps(cleanup);
      if (_bodyLabel != null) {
        _indent--;
        _line('}');
      }
      _line('');
    }
    if (_bodyLabel != null) _dropUnusedLabel(bodyAt, _bodyLabel!);
    _bodyLabel = null;
    _cleanupFrom = null;
    _cleanupEntriesOf = const {};
  }

  String _typeComment(SeqVariable v, {String? rawDefault}) {
    final t = v.type;
    final c = v.comment;
    final parts = [
      if (t != null) t,
      if (rawDefault != null) "default: ${_comment(rawDefault)}",
      if (c != null) _comment(c),
    ];
    if (parts.isEmpty) return '';
    return ' // ${parts.join(' — ')}';
  }

  (_DartSlot, String, String)? _scalarDecl(SeqVariable v, String id) {
    final scalar = _scalarType(v);
    if (scalar == null) return null;
    var (type, zero) = scalar;
    if (type == _DartSlot.number && _idTypes[id] == _DartSlot.integer) type = _DartSlot.integer;
    return (type, zero, _scalarInit(v, type, zero));
  }

  String _paramDecl(SeqVariable p, String id) {
    final scalar = _scalarDecl(p, id);
    if (scalar != null) {
      final (type, _, init) = scalar;
      return '${type.source} $id = $init';
    }
    if (_isArrayVar(p)) return 'List<dynamic>? $id';
    return 'dynamic $id';
  }

  String _localDecl(SeqVariable local, String id, bool assigned) {
    final scalar = _scalarDecl(local, id);
    if (scalar != null) {
      final (type, zero, init) = scalar;
      final fellBack = local.value != null && init == zero && type != _DartSlot.text;
      return '${assigned ? '' : 'const '}${type.source} $id = $init;'
          '${_typeComment(local, rawDefault: fellBack ? local.value : null)}';
    }
    if (_isArrayVar(local)) {
      return '${assigned ? '' : 'final '}List<dynamic> $id = ${_arrayInit(local)};${_typeComment(local)}';
    }
    if (_isNullLocal(local)) {
      return '${assigned ? 'dynamic $id;' : 'const dynamic $id = null;'}${_typeComment(local)}';
    }
    return '${assigned ? '' : 'final '}dynamic $id = ${_propObjInit(local.raw, {})};${_typeComment(local)}';
  }

  static final _identifier = RegExp(r'(?<![\w$.])[A-Za-z_$][\w$]*(?![\w$])');
  static final _assignedAfter = RegExp(r'\s*(?:[-+*/%~]?=(?!=)|\?\?=|\+\+|--)');
  static final _assignedBefore = RegExp(r'(?:\+\+|--)$');
  static final _label = RegExp(r'\s*:');

  static final _identifierStart = RegExp(r'[A-Za-z_]\w*');

  static String _codeOnly(String source) {
    final out = StringBuffer();
    late int Function(int at, String? close) code;
    int literal(int at, String quote) {
      while (at < source.length) {
        final c = source[at];
        final name = c == r'$' ? _identifierStart.matchAsPrefix(source, at + 1) : null;
        if (c == r'\') {
          at += 2;
        } else if (c == quote) {
          return at + 1;
        } else if (c == r'$' && source.startsWith('{', at + 1)) {
          out.write(' ');
          at = code(at + 2, '}');
          out.write(' ');
        } else if (name != null) {
          out.write(' ${name[0]} ');
          at = name.end;
        } else {
          at++;
        }
      }
      return at;
    }

    code = (at, close) {
      var depth = 0;
      while (at < source.length) {
        final c = source[at];
        if (c == "'" || c == '"') {
          out.write(' ');
          at = literal(at + 1, c);
          continue;
        }
        if (c == '{') depth++;
        if (c == '}' && depth-- == 0 && close != null) return at + 1;
        out.write(c);
        at++;
      }
      return at;
    };
    code(0, null);
    return out.toString();
  }

  static (Set<String>, Set<String>) _accesses(String body) {
    final code = _codeOnly(_withoutLineComments(body));
    final assigned = <String>{}, read = <String>{};
    for (final m in _identifier.allMatches(code)) {
      if (_label.matchAsPrefix(code, m.end) != null) continue;
      if (_assignedBefore.hasMatch(code.substring(0, m.start))) {
        assigned.add(m[0]!);
        read.add(m[0]!);
      } else {
        (_assignedAfter.matchAsPrefix(code, m.end) != null ? assigned : read).add(m[0]!);
      }
    }
    return (assigned, read);
  }

  static final _assignTarget = RegExp(r'^([A-Za-z_$][\w$]*)\s*(?:[-+*/%~]?=(?!=)|\?\?=|\+\+|--)');

  String _unreadLine(String statement) {
    final m = _assignTarget.firstMatch(statement);
    final rhs = m == null ? '' : statement.substring(m.end).trim();
    if (rhs.isEmpty || _accesses(rhs).$2.difference(const {'true', 'false', 'null'}).isEmpty) {
      return '// never read: $statement;';
    }
    return '${_constantCondition(rhs) ? 'const' : 'final'} _ = $rhs; // never read: ${m![1]}';
  }

  bool _unread(String statement) {
    final code = _codeOnly(statement);
    return _writeOnly.any(
      (id) => RegExp('(?<![\\w\$.])${RegExp.escape(id)}\\s*(?:[-+*/%~]?=(?!=)|\\?\\?=|\\+\\+|--)').hasMatch(code),
    );
  }

  String _arrayInit(SeqVariable v) => _listInit(v.raw, {});

  void _emitSteps(List<Step> steps) {
    final plan = _gotoPlan(steps);
    _gotoLabels = plan.sites;
    final openJumps = <_JumpBlock>[];
    void boundary(int index) {
      while (openJumps.isNotEmpty && openJumps.last.close == index) {
        final closing = openJumps.removeLast();
        if (closing.footer != null && !_endsInJump()) _line(closing.footer!);
        _indent--;
        _line('}');
      }
      for (final block in plan.blocks.where((b) => b.open == index)) {
        _line(block.header);
        _indent++;
        openJumps.add(block);
      }
    }

    final open = <_OpenBlock>[];
    var selectCounter = 0;
    final selectVars = <int, ({String value, String matched})>{};
    const loopKinds = {
      FlowKind.whileLoop,
      FlowKind.doWhile,
      FlowKind.forLoop,
      FlowKind.forEach,
    };

    _OpenBlock? innermost(bool Function(FlowKind) test) {
      for (var i = open.length - 1; i >= 0; i--) {
        if (test(open[i].kind)) return open[i];
      }
      return null;
    }

    void closeBlock(_OpenBlock opened, {String note = ''}) {
      if (opened.labelAt >= 0) _dropUnusedLabel(opened.labelAt, opened.label ?? 'sel${opened.selectId}');
      if (opened.kind == FlowKind.forLoop && opened.increment != null) {
        _line('${_exprStatement(opened.increment!)}; // for increment');
      }
      for (var i = 1; i < opened.closers; i++) {
        _indent--;
        _line('}');
      }
      _indent--;
      if (opened.kind == FlowKind.doWhile) {
        _line('} while (${_cond(opened.condition ?? 'true')});$note');
      } else {
        _line('}$note');
      }
    }

    const defaultFlowNames = {
      'If',
      'Else',
      'Else If',
      'While',
      'Do While',
      'For',
      'For Each',
      'Select',
      'Case',
      'Sweep Loop',
      'End',
      'Break',
      'Continue',
      'Statement',
      'Goto',
    };
    for (final (index, step) in steps.indexed) {
      boundary(index);
      final flow = step.flowControl;
      final rawName = _comment(step.name);
      final authorComment = step.comment;
      if (authorComment != null) {
        for (final line in authorComment.split('\n')) {
          _line('// ${_comment(line)}');
        }
      }
      final mode = step.settings.mode;
      var modeNote = '';
      if (!step.settings.isNormalMode) {
        final structural = flow != null && flow.kind != FlowKind.breakStmt && flow.kind != FlowKind.continueStmt;
        if (!structural) {
          final what = switch (mode) {
            'Skip' => 'skipped',
            'Pass' => 'force-pass',
            'Fail' => 'force-fail',
            _ => 'mode $mode',
          };
          _line('// [$what in source] $rawName');
          continue;
        }
        modeNote = ' [$mode in source]';
      }
      var nameNote = defaultFlowNames.contains(rawName) ? '' : ' // $rawName';
      if (modeNote.isNotEmpty) {
        nameNote = nameNote.isEmpty ? ' //$modeNote' : '$nameNote$modeNote';
      }
      if (flow == null) {
        _loopDepth = open.where((o) => loopKinds.contains(o.kind) || o.kind == FlowKind.sweepLoop).length;
        _emitPlainStep(step);
        continue;
      }
      switch (flow.kind) {
        case FlowKind.ifBlock:
          _line('if (${_cond(flow.condition ?? 'true')}) {$nameNote');
          _indent++;
          open.add(_openBlock(flow.kind));
        case FlowKind.elseIf:
          if (open.isEmpty || open.last.kind != FlowKind.ifBlock) {
            _line(
              '// $rawName: Else-If without an open If (unbalanced source) — '
              'kept as a comment',
            );
            continue;
          }
          _indent--;
          _line(
            '} else if (${_cond(flow.condition ?? 'true')}) '
            '{$nameNote',
          );
          _indent++;
        case FlowKind.elseBlock:
          if (open.isEmpty || open.last.kind != FlowKind.ifBlock) {
            _line(
              '// $rawName: Else without an open If (unbalanced source) — '
              'kept as a comment',
            );
            continue;
          }
          _indent--;
          _line('} else {$nameNote');
          _indent++;
        case FlowKind.whileLoop:
          _line(
            'while (${_cond(flow.condition ?? 'true')}) '
            '{$nameNote',
          );
          _indent++;
          open.add(_openBlock(flow.kind));
        case FlowKind.doWhile:
          _line('do {$nameNote');
          _indent++;
          open.add(_openBlock(flow.kind, condition: flow.condition ?? 'true'));
        case FlowKind.forLoop:
          final init = flow.initialization;
          var initDart = init != null ? _exprStatement(init) : null;
          var incrDart = flow.increment != null ? _exprStatement(flow.increment!) : null;
          final unread = [
            if (initDart != null && _unread(initDart)) initDart,
            if (incrDart != null && _unread(incrDart)) incrDart,
          ];
          if (unread.isNotEmpty) {
            unread.map(_unreadLine).forEach(_line);
            if (initDart != null && _unread(initDart)) initDart = null;
            if (incrDart != null && _unread(incrDart)) incrDart = null;
          }
          final canFor =
              (initDart == null || !initDart.startsWith('ts.eval(')) &&
              (incrDart == null || !incrDart.startsWith('ts.eval('));
          if (canFor && (initDart != null || incrDart != null)) {
            _line(
              'for (${initDart ?? ''}; '
              '${_cond(flow.condition ?? 'true')}; ${incrDart ?? ''}) '
              '{$nameNote',
            );
            _indent++;
            open.add(_openBlock(flow.kind));
          } else {
            if (initDart != null) {
              _line('$initDart;${nameNote.isEmpty ? ' // init' : '$nameNote (init)'}');
            }
            _line(
              'while (${_cond(flow.condition ?? 'true')}) '
              '{$nameNote',
            );
            _indent++;
            open.add(_openBlock(flow.kind, increment: incrDart == null ? null : flow.increment));
          }
        case FlowKind.forEach:
          final array = flow.arrayExpr ?? '[]';
          final loopVar = _claimId('element');
          final element = flow.arrayElement;
          final target = _elementTarget(element);
          String? bind;
          if (target != null) {
            final cast = switch (target.type) {
              _DartSlot.number => '($loopVar as num).toDouble()',
              _DartSlot.integer => '($loopVar as num).toInt()',
              _DartSlot.flag => '$loopVar as bool',
              _DartSlot.text => '$loopVar as String',
              _DartSlot.list => '$loopVar as List<dynamic>',
              _ => loopVar,
            };
            bind = '${target.code} = $cast;';
          }
          final bound = bind != null && !_unread(bind);
          _line(
            'for (final ${bound ? loopVar : '_'} in ts.iterate(${_expr(array)})) '
            '{$nameNote',
          );
          _indent++;
          if (bind != null) {
            _line(bound ? bind : '// never read: $bind');
          } else if (element != null) {
            _line('// TODO: bind loop element: ${_comment(element)} = <element>');
          }
          open.add(_openBlock(flow.kind));
        case FlowKind.selectBlock:
          selectCounter++;
          selectVars[selectCounter] = (
            value: _claimId('select$selectCounter'),
            matched: _claimId('matched$selectCounter'),
          );
          final labelAt = _out.length + 2 * _indent;
          _line('sel$selectCounter: {$nameNote');
          _indent++;
          _line(
            '${_isConstant(_expr(flow.itemExpression ?? 'null')) ? 'const' : 'final'} ${selectVars[selectCounter]!.value} = '
            '${_expr(flow.itemExpression ?? 'null')};',
          );
          _line('var ${selectVars[selectCounter]!.matched} = false;');
          open.add(_openBlock(flow.kind, selectId: selectCounter, labelAt: labelAt));
        case FlowKind.caseBlock:
          final select = innermost((k) => k == FlowKind.selectBlock)?.selectId ?? 0;
          if (select == 0) {
            _line(
              '// $rawName: Case without an open Select (unbalanced source) '
              '— kept as a comment',
            );
            continue;
          }
          final vars = selectVars[select]!;
          if (flow.isDefaultCase) {
            _line('if (!${vars.matched}) {${nameNote.isEmpty ? ' // default case' : '$nameNote (default)'}');
          } else {
            _line(
              'if (!${vars.matched} && ${vars.value} == '
              '${_expr(flow.itemExpression ?? 'null')}) {$nameNote',
            );
          }
          _indent++;
          _line('${vars.matched} = true;');
          open.add(_openBlock(flow.kind, selectId: select));
        case FlowKind.sweepLoop:
          final levels = step.sweepLoop == null ? null : _sweepLevels(step.sweepLoop!);
          if (levels == null) {
            _line('// TODO: ${_comment(flow.header)} not exported; the body runs once');
            _line('{$nameNote');
            _indent++;
            open.add(_openBlock(flow.kind));
          } else {
            final label = _claimId('sweep');
            final labelAt = _out.length + 2 * _indent;
            for (final (depth, level) in levels.indexed) {
              final value = _claimId('value');
              final source = level.length == 1
                  ? level.single.values
                  : 'ts.parallel([${level.map((p) => p.values).join(', ')}])';
              final binds = [
                for (final (column, parameter) in level.indexed)
                  parameter.bind(level.length == 1 ? value : '$value[$column]'),
              ];
              _line(
                '${depth == 0 ? '$label: ' : ''}'
                'for (final ${binds.every(_unread) ? '_' : value} in $source) {${depth == 0 ? nameNote : ''}',
              );
              _indent++;
              for (final bind in binds) {
                _line(_unread(bind) ? '// never read: $bind' : bind);
              }
            }
            open.add(_openBlock(flow.kind, label: label, closers: levels.length, labelAt: labelAt));
          }
        case FlowKind.end:
          if (open.isEmpty) {
            _line(
              '// $rawName: NI_Flow_End without an open block '
              '(unbalanced in source)',
            );
            continue;
          }
          closeBlock(open.removeLast(), note: nameNote);
        case FlowKind.breakStmt:
          final target = innermost(
            (k) => k == FlowKind.selectBlock || k == FlowKind.sweepLoop || loopKinds.contains(k),
          );
          if (target?.kind == FlowKind.sweepLoop && target?.label == null) {
            _line('// $rawName: Break out of a sweep loop — kept as a comment');
          } else if (target == null) {
            _line(
              '// $rawName: Break with no enclosing loop/select — kept as a '
              'comment',
            );
          } else {
            final breakStmt = switch (target.kind) {
              FlowKind.selectBlock => 'break sel${target.selectId};',
              FlowKind.sweepLoop => 'break ${target.label};',
              _ => 'break;',
            };
            final pre = step.settings.precondition ?? _typePreconditions[step.type];
            if (pre != null) {
              _line('if (${_cond(pre)}) {$nameNote');
              _indent++;
              _line(breakStmt);
              _indent--;
              _line('}');
            } else {
              _line('$breakStmt$nameNote');
            }
          }
        case FlowKind.continueStmt:
          final loop = innermost((k) => k == FlowKind.sweepLoop || loopKinds.contains(k));
          if (loop?.kind == FlowKind.sweepLoop && loop?.label == null) {
            _line('// $rawName: Continue in a sweep loop — kept as a comment');
          } else if (loop == null) {
            _line(
              '// $rawName: Continue with no enclosing loop — kept as a '
              'comment',
            );
          } else {
            final pre = step.settings.precondition ?? _typePreconditions[step.type];
            if (pre != null) {
              _line('if (${_cond(pre)}) {$nameNote');
              _indent++;
            }
            if (loop.kind == FlowKind.forLoop && loop.increment != null) {
              _line(
                '${_exprStatement(loop.increment!)}; // for increment '
                '(before continue)',
              );
            }
            _line('continue;${pre == null ? nameNote : ''}');
            if (pre != null) {
              _indent--;
              _line('}');
            }
          }
      }
    }
    while (open.isNotEmpty) {
      closeBlock(open.removeLast(), note: ' // closed: unbalanced block in source');
    }
    boundary(steps.length);
    _gotoLabels = Map.identity();
  }

  static String? _jumpTarget(String? raw) {
    final target = raw == null ? null : unwrapExprString(raw);
    return target == null || target.isEmpty ? null : target;
  }

  static List<(String?, String?)> _postActions(StepSettings settings) => settings.customExpression != null
      ? [
          (settings.customTrueAction, settings.customTrueTarget),
          (settings.customFalseAction, settings.customFalseTarget),
        ]
      : [(settings.passAction, settings.passActionTarget), (settings.failAction, settings.failActionTarget)];

  static bool _targetsCleanup(Step step) =>
      step.settings.isNormalMode &&
      _postActions(step.settings).any((a) => a.$1 == 'Goto' && _jumpTarget(a.$2) == _cleanupTarget);

  static const _endTarget = '<End>';
  static const _cleanupTarget = '<Cleanup>';

  static List<List<int>> _blockContexts(List<Step> steps) {
    final contexts = <List<int>>[];
    final stack = <(int, FlowKind)>[];
    var segment = 0;
    for (final step in steps) {
      contexts.add([for (final (id, _) in stack) id]);
      final kind = step.flowControl?.kind;
      if (kind == null) continue;
      if (kind.opensBlock) {
        stack.add((++segment, kind));
      } else if (kind.isContinuation && stack.isNotEmpty && stack.last.$2 == FlowKind.ifBlock) {
        stack[stack.length - 1] = (++segment, FlowKind.ifBlock);
      } else if (kind == FlowKind.end && stack.isNotEmpty) {
        stack.removeLast();
      }
    }
    contexts.add([for (final (id, _) in stack) id]);
    return contexts;
  }

  static bool _within(List<int> inner, List<int> outer) {
    if (inner.length < outer.length) return false;
    for (var i = 0; i < outer.length; i++) {
      if (inner[i] != outer[i]) return false;
    }
    return true;
  }

  static int? _stepIndex(List<Step> steps, String target) {
    final matches = [
      for (final (i, candidate) in steps.indexed)
        if (candidate.name == target || candidate.id == target) i,
    ];
    return matches.length == 1 ? matches.single : null;
  }

  int? _cleanupEntry(String target) {
    final cleanup = _sequence?.cleanup ?? const <Step>[];
    final at = _stepIndex(cleanup, target);
    return at != null && _blockContexts(cleanup)[at].isEmpty ? at : null;
  }

  Set<int> _cleanupEntries(Sequence sequence) {
    final entries = <int>{};
    for (final group in const [StepGroup.setup, StepGroup.main]) {
      final steps = sequence.stepsIn(group);
      for (final step in steps) {
        if (step.flowControl != null || !step.settings.isNormalMode) continue;
        for (final (action, raw) in _postActions(step.settings)) {
          final target = _jumpTarget(raw);
          if (action != 'Goto' || target == null || target == _endTarget || target == _cleanupTarget) continue;
          if (_stepIndex(steps, target) != null) continue;
          final at = _cleanupEntry(target);
          if (at != null && at > 0) entries.add(at);
        }
      }
    }
    return entries;
  }

  ({List<_JumpBlock> blocks, Map<SeqProperty, Map<String, String>> sites}) _gotoPlan(List<Step> steps) {
    final contexts = _blockContexts(steps);
    final blocks = <_JumpBlock>[];
    bool laminar(int open, int close) => blocks.every(
      (b) =>
          close <= b.open ||
          open >= b.close ||
          (open >= b.open && close <= b.close) ||
          (open <= b.open && close >= b.close),
    );
    final sites = Map<SeqProperty, Map<String, String>>.identity();
    final forward = <int, String>{};
    final backward = <(int, int), String>{};
    if (_group == StepGroup.cleanup && _cleanupFrom != null) {
      final entries = _cleanupEntriesOf.toList()..sort();
      for (final (i, entry) in entries.indexed) {
        final from = i == 0 ? 0 : entries[i - 1];
        if (laminar(from, entry)) {
          blocks.add((open: from, close: entry, header: 'if ($_cleanupFrom < $entry) {', footer: null));
        }
      }
    }
    for (final (site, step) in steps.indexed) {
      if (step.flowControl != null || !step.settings.isNormalMode) continue;
      for (final (action, raw) in _postActions(step.settings)) {
        final target = _jumpTarget(raw);
        if (action != 'Goto' || target == null || target == _cleanupTarget) continue;
        final at = target == _endTarget ? steps.length : _stepIndex(steps, target);
        if (at == null) {
          final entry = _group == StepGroup.cleanup || _bodyLabel == null ? null : _cleanupEntry(target);
          if (entry != null && (entry == 0 || _cleanupFrom != null)) {
            (sites[step.raw] ??= {})[target] = entry == 0
                ? 'break $_bodyLabel;'
                : '$_cleanupFrom = $entry; break $_bodyLabel;';
          }
          continue;
        }
        final kind = at < steps.length ? steps[at].flowControl?.kind : null;
        if (kind != null && kind.isContinuation) continue;
        if (!_within(contexts[site], contexts[at])) continue;
        if (at > site) {
          var start = at;
          while (start > 0 && _within(contexts[start - 1], contexts[at])) {
            start--;
          }
          if (site < start) continue;
          var label = forward[at];
          if (label == null) {
            if (!laminar(start, at)) continue;
            label = forward[at] = _claimId(
              at == steps.length ? 'end${_group.key}' : 'skipTo${dartIdentifier(steps[at].name, capitalize: true)}',
            );
            blocks.add((open: start, close: at, header: '$label: {', footer: null));
          }
          (sites[step.raw] ??= {})[target] = 'break $label;';
        } else {
          var close = site + 1;
          while (close < steps.length && !_sameContext(contexts[close], contexts[at])) {
            close++;
          }
          if (!_sameContext(contexts[close], contexts[at])) continue;
          final escapes = [
            for (var i = at; i < close; i++)
              if (steps[i].flowControl?.kind case FlowKind.breakStmt || FlowKind.continueStmt) i,
          ].any((i) => contexts[i].length == contexts[at].length);
          if (escapes) continue;
          var label = backward[(at, close)];
          if (label == null) {
            if (!laminar(at, close)) continue;
            label = backward[(at, close)] = _claimId('backTo${dartIdentifier(steps[at].name, capitalize: true)}');
            blocks.add((open: at, close: close, header: '$label: while (true) {', footer: 'break $label;'));
          }
          (sites[step.raw] ??= {})[target] = 'continue $label;';
        }
      }
    }
    blocks.sort((a, b) => a.open != b.open ? a.open.compareTo(b.open) : b.close.compareTo(a.close));
    return (blocks: blocks, sites: sites);
  }

  static bool _sameContext(List<int> a, List<int> b) => a.length == b.length && _within(a, b);

  String? _postActionCode(Step step, String? action, String? rawTarget) {
    final target = _jumpTarget(rawTarget);
    switch (action) {
      case null || 'Next':
        return '';
      case 'Terminate':
        return 'ts.terminate();';
      case 'Goto' when target == _cleanupTarget:
        return _group != StepGroup.cleanup && _bodyLabel != null ? 'break $_bodyLabel;' : null;
      case 'Goto':
        return _gotoLabels[step.raw]?[target];
      case 'Cback':
        final fn = target == null ? null : _sequenceFnNames[target];
        return fn == null ? null : 'await $fn();';
      default:
        return null;
    }
  }

  void _emitPostAction(Step step, String? result) {
    final settings = step.settings;
    final actions = _postActions(settings);
    final codes = [for (final (action, target) in actions) _postActionCode(step, action, target)];
    if (codes.every((c) => c == '')) return;
    final custom = settings.customExpression;
    if (codes.contains(null) || (custom == null && result == null)) return;
    final [onTrue!, onFalse!] = codes;
    final folded = custom == null ? null : _condition(custom);
    final condition = custom != null ? _cond(custom) : "$result.Status == 'Passed'";
    if (folded == 'true' || folded == 'false') {
      final taken = folded == 'true' ? onTrue : onFalse;
      if (taken.isNotEmpty) _line('$taken // post action');
      return;
    }
    final otherwise = custom != null ? null : "$result.Status == 'Failed'";
    final arms = [
      if (onTrue.isNotEmpty) (condition, onTrue),
      if (onFalse.isNotEmpty) (otherwise ?? (onTrue.isEmpty ? _negate(condition) : null), onFalse),
    ];
    for (final (i, (test, code)) in arms.indexed) {
      final head = test == null ? '} else {' : (i == 0 ? 'if ($test) {' : '} else if ($test) {');
      _line(i == 0 ? '$head // post action' : head);
      _line('  $code');
    }
    _line('}');
  }

  List<List<({String values, String Function(String value) bind})>>? _sweepLevels(SweepLoop sweep) {
    final unsupported =
        sweep.input?.enabled == true ||
        sweep.output?.enabled == true ||
        (sweep.ioSessionCount ?? 0) > 0 ||
        sweep.iterationExpression != null ||
        sweep.offsetExpression != null ||
        sweep.enabledTestVectors != null;
    if (unsupported) return null;
    final active = [
      for (final p in sweep.parameters)
        if (p.strategy != 'UseExistingValue' && p.enabled != false) p,
    ];
    if (active.isEmpty || (active.length > 1 && active.any((p) => p.level == null))) return null;
    final byLevel = <int, List<({String values, String Function(String value) bind})>>{};
    for (final parameter in active) {
      final target = parameter.valueExpression;
      final parsed = target == null ? null : parseSeqExpression(target);
      final slot = parsed == null ? null : _emitTarget(parsed);
      if (slot == null || slot.type == _DartSlot.absent || slot.type == _DartSlot.opaque) return null;
      String? values;
      final operation = parameter.stepOperation;
      String bound(String? raw) => _numeric(raw ?? '0');
      switch (_SweepStrategy.byName[parameter.strategy]) {
        case _SweepStrategy.startStopStep when operation == 'Linear':
          values =
              'ts.sweepSteps(${bound(parameter.startExpression)}, ${bound(parameter.stopExpression)}, '
              '${bound(parameter.stepExpression)})';
        case _SweepStrategy.startStopNumPoints when operation == 'Linear' || operation == 'Logarithmic':
          values =
              'ts.sweepPoints(${bound(parameter.startExpression)}, ${bound(parameter.stopExpression)}, '
              '${bound(parameter.sweepPointsExpression)}${operation == 'Logarithmic' ? ', logarithmic: true' : ''})';
        case _SweepStrategy.array:
          final array = parameter.arrayExpression == null ? null : _translate(parameter.arrayExpression!);
          if (array != null && (array.type == _DartSlot.list || array.type == _DartSlot.untyped)) values = array.code;
        default:
      }
      if (values == null) return null;
      final cast = switch (slot.type) {
        _DartSlot.number => (String v) => '($v as num).toDouble()',
        _DartSlot.integer => (String v) => '($v as num).toInt()',
        _DartSlot.flag => (String v) => '$v as bool',
        _DartSlot.text => (String v) => '$v as String',
        _DartSlot.list => (String v) => '$v as List<dynamic>',
        _ => (String v) => v,
      };
      (byLevel[parameter.level ?? 0] ??= []).add((values: values, bind: (v) => '${slot.code} = ${cast(v)};'));
    }
    return [for (final level in byLevel.keys.toList()..sort()) byLevel[level]!];
  }

  String _exprStatement(String raw) {
    if (_stripComments(raw).trim().isEmpty) return "''";
    final parsed = parseSeqExpression(raw);
    _statementRoot = parsed;
    final code = parsed == null || parsed is SeqSequence ? null : _emit(parsed)?.code;
    _statementRoot = null;
    return code == null ? _evalFallback(raw) : _typed(code, raw);
  }

